create or replace function public.carregar_operacao_garcom(p_telefone text,p_pin text)
returns jsonb
language plpgsql
security definer
set search_path='public'
as $$
declare
v_m public.equipe_operacional%rowtype;
v_est public.estabelecimentos%rowtype;
v_count integer;
begin
select count(*) into v_count
from public.equipe_operacional m
where regexp_replace(m.telefone,'\D','','g')=regexp_replace(p_telefone,'\D','','g')
and m.pin=p_pin and m.funcao='garcom' and m.ativo=true;
if v_count<>1 then raise exception 'Acesso do garçom inválido ou ambíguo'; end if;
select * into v_m
from public.equipe_operacional m
where regexp_replace(m.telefone,'\D','','g')=regexp_replace(p_telefone,'\D','','g')
and m.pin=p_pin and m.funcao='garcom' and m.ativo=true
limit 1;
select * into v_est from public.estabelecimentos where id=v_m.estabelecimento_id;
return jsonb_build_object(
'estabelecimento',jsonb_build_object(
'id',v_est.id,'nome',v_est.nome,'slug',v_est.slug,'aberto',v_est.aberto,
'taxa_entrega',v_est.taxa_entrega,'pedido_minimo',v_est.pedido_minimo
),
'produtos',coalesce((
select jsonb_agg(jsonb_build_object(
'id',p.id,'nome',p.nome,'descricao',p.descricao,'preco',p.preco,
'categoria',coalesce(c.nome,'Sem categoria'),'imagem_url',p.imagem_url,'destaque',p.destaque
) order by coalesce(c.ordem,999),p.nome)
from public.produtos p left join public.categorias c on c.id=p.categoria_id
where p.estabelecimento_id=v_est.id and p.ativo=true
),'[]'::jsonb),
'mesas',coalesce((
select jsonb_agg(jsonb_build_object(
'id',m.id,'numero',m.numero,'nome',m.nome,'token',m.codigo_qr
) order by m.numero)
from public.mesas m where m.estabelecimento_id=v_est.id and m.ativo=true
),'[]'::jsonb),
'pedidos',coalesce((
select jsonb_agg(x.obj order by x.created_at desc)
from (
select p.created_at,jsonb_build_object(
'id',p.id,'codigo',p.codigo,'numero',p.numero,'status',p.status,'tipo',p.tipo,
'total',p.total,'created_at',p.created_at,'mesa_id',p.mesa_id,
'cliente_nome',c.nome,'cliente_telefone',c.telefone,
'mesa_nome',m.nome,'mesa_numero',m.numero,
'itens',coalesce((
select jsonb_agg(jsonb_build_object(
'quantidade',i.quantidade,'nome',i.nome_produto,'nome_produto',i.nome_produto,
'observacoes',i.observacoes,'total',i.total
) order by i.id)
from public.itens_pedido i where i.pedido_id=p.id
),'[]'::jsonb)
) obj
from public.pedidos p
left join public.clientes c on c.id=p.cliente_id
left join public.mesas m on m.id=p.mesa_id
where p.estabelecimento_id=v_est.id
order by p.created_at desc limit 150
) x
),'[]'::jsonb)
);
end;
$$;
