create or replace function public.registrar_evento_operacional_pedido()
returns trigger
language plpgsql
security definer
set search_path='public'
as $$
declare
v_origem text:=public.fsdelivery_origem_operacao();
v_responsavel uuid:=public.fsdelivery_responsavel_operacao();
v_destino text;
v_titulo text;
v_mensagem text;
v_codigo text;
begin
if tg_op='UPDATE' and old.status is not distinct from new.status then
return new;
end if;
v_codigo:=coalesce(new.codigo,new.id::text);
insert into public.pedido_eventos(
pedido_id,estabelecimento_id,status_anterior,status_novo,origem,responsavel_id
) values (
new.id,new.estabelecimento_id,
case when tg_op='INSERT' then null else old.status end,
new.status,v_origem,v_responsavel
);
if new.status='aguardando_aprovacao' then
v_destino:='caixa';
v_titulo:='Pedido aguardando aprovação';
v_mensagem:='Pedido #'||v_codigo||' precisa ser aprovado antes do preparo.';
elsif new.status in ('confirmado','novo') then
v_destino:='cozinha';
v_titulo:='Novo pedido na cozinha';
v_mensagem:='Pedido #'||v_codigo||' foi liberado para produção.';
elsif new.status='pronto' then
if new.tipo in ('mesa','local') then
v_destino:='garcom';
v_titulo:='Pedido pronto para servir';
v_mensagem:='Pedido #'||v_codigo||' está pronto para levar à mesa.';
elsif new.tipo='entrega' then
v_destino:='entregador';
v_titulo:='Pedido pronto para entrega';
v_mensagem:='Pedido #'||v_codigo||' está liberado para iniciar a entrega.';
else
v_destino:='caixa';
v_titulo:='Pedido pronto para retirada';
v_mensagem:='Pedido #'||v_codigo||' está pronto para retirada.';
end if;
elsif new.status='saiu_entrega' then
v_destino:='admin';
v_titulo:='Entrega iniciada';
v_mensagem:='Pedido #'||v_codigo||' saiu para entrega.';
elsif new.status in ('finalizado','entregue') then
v_destino:='admin';
v_titulo:='Pedido finalizado';
v_mensagem:='Pedido #'||v_codigo||' foi concluído.';
elsif new.status='cancelado' then
v_destino:='admin';
v_titulo:='Pedido cancelado';
v_mensagem:='Pedido #'||v_codigo||' foi cancelado.';
end if;
if v_destino is not null then
insert into public.notificacoes_operacionais(
estabelecimento_id,pedido_id,destinatario,tipo,titulo,mensagem,chave_deduplicacao
) values (
new.estabelecimento_id,new.id,v_destino,new.status,v_titulo,v_mensagem,
concat(new.id,':',new.status,':',v_destino)
) on conflict do nothing;
end if;
return new;
end;
$$;
