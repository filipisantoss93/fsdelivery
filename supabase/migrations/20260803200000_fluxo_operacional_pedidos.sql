create or replace function public.listar_entregas_equipe(p_slug text,p_telefone text,p_pin text)
returns table(
id bigint,codigo text,status text,total numeric,endereco_entrega jsonb,
cliente_nome text,cliente_telefone text,created_at timestamptz,
latitude double precision,longitude double precision,ordem_rota integer,
distancia_estimada_km numeric,duracao_estimada_min integer,
saiu_para_entrega_em timestamptz,entregue_em timestamptz
)
language plpgsql
security definer
set search_path='public'
as $$
declare v_m public.equipe_operacional%rowtype; v_est uuid;
begin
select e.id into v_est from public.estabelecimentos e where e.slug=p_slug;
select * into v_m from public.equipe_operacional
where estabelecimento_id=v_est
and regexp_replace(telefone,'\D','','g')=regexp_replace(p_telefone,'\D','','g')
and pin=p_pin and ativo=true and funcao='entregador' limit 1;
if not found then raise exception 'Acesso inválido'; end if;
return query
select p.id,p.codigo,p.status,p.total,p.endereco_entrega,c.nome,c.telefone,p.created_at,
p.latitude,p.longitude,p.ordem_rota,p.distancia_estimada_km,p.duracao_estimada_min,
p.saiu_para_entrega_em,p.entregue_em
from public.pedidos p
left join public.clientes c on c.id=p.cliente_id
where p.estabelecimento_id=v_est
and p.tipo='entrega'
and (
(p.status in ('preparo','pronto') and (p.entregador_id is null or p.entregador_id=v_m.id)) or
(p.status='saiu_entrega' and p.entregador_id=v_m.id) or
(p.status in ('finalizado','entregue') and p.entregador_id=v_m.id and coalesce(p.entregue_em,p.atualizado_em)::date=current_date)
)
order by case p.status
when 'saiu_entrega' then 0 when 'pronto' then 1 when 'preparo' then 2 else 3 end,
p.ordem_rota nulls last,p.created_at;
end;
$$;
